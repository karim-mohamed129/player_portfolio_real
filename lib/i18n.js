export function normalizeLocale(value) {
  const locale = String(value || "").toLowerCase().split("-")[0];
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function getDirection(locale) {
  return localeMeta[normalizeLocale(locale)].direction;
}

export function getHtmlLang(locale) {
  return localeMeta[normalizeLocale(locale)].htmlLang;
}

export function getNextLocale(locale) {
  return normalizeLocale(locale) === "ar" ? "en" : "ar";
}

export function getNestedTranslation(dictionary, key) {
  return String(key || "")
    .split(".")
    .filter(Boolean)
    .reduce((value, part) => (value && typeof value === "object" ? value[part] : undefined), dictionary);
}
